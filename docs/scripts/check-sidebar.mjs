// Guard: every docs page must be reachable from the sidebar, every
// sidebar slug must exist, and every internal link must carry the
// `/soma` base AND land on a page that exists.
//
// Orphaned pages build fine and are linkable by URL, so nothing else
// catches them — that is how three feature pages once stayed invisible.
// Base-less links are worse: they build, they look right in `npm run
// dev` (where there is no base), and they 404 only in production — that
// is how six links to the experiment-pool page shipped broken.
//
// Where the link *points* went unchecked until the pages were reorganised
// and 43 of them turned out to be aimed at paths that had moved or at
// pages that had been deleted. Every one of those carried the base, so
// the base check passed them; astro builds them; they 404 on click. The
// two halves of that check are not the same check.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DOCS = 'src/content/docs';
const BASE = '/soma';

function walk(dir) {
	return readdirSync(dir).flatMap((entry) => {
		const full = join(dir, entry);
		return statSync(full).isDirectory() ? walk(full) : [full];
	});
}

const files = walk(DOCS).filter((f) => /\.mdx?$/.test(f));

const pages = files
	.map((f) => relative(DOCS, f).replace(/\.mdx?$/, '').split(sep).join('/'))
	.filter((slug) => slug !== 'index');

// Every root-relative link in a page, from both places one can be written.
//
// Markdown syntax is the obvious one. The other is a bare `link:` value in
// frontmatter — the splash page's hero buttons are written that way, and both
// checks below used to read markdown only, which is how the home page's own
// "Get Started" button went on pointing at a page that had been moved. A link
// nobody wrote in brackets is still a link.
const hrefs = files.flatMap((file) => {
	const text = readFileSync(file, 'utf8');
	const found = [
		...[...text.matchAll(/]\((\/[^)\s]*)\)/g)].map((m) => m[1]),
		...[...text.matchAll(/^\s*link:\s*(\/\S*)\s*$/gm)].map((m) => m[1]),
	];
	return found.map((href) => ({ file: relative('.', file), href }));
});

// Anything pointing at another origin, an anchor, or the base itself is fine.
const baseless = hrefs.filter(
	({ href }) => href !== BASE && !href.startsWith(`${BASE}/`),
);

// And a link that DOES carry the base must reach a page. The `/soma/api/` tree
// is cargo-doc output, copied in by the deploy workflow and absent from this
// build, so it is taken on trust — the deploy step that puts it there is what
// makes it true.
const dangling_links = hrefs
	.filter(({ href }) => href.startsWith(`${BASE}/`) && !href.startsWith(`${BASE}/api/`))
	.map((x) => ({ ...x, slug: x.href.slice(BASE.length + 1).split('#')[0].replace(/\/$/, '') }))
	.filter(({ slug }) => slug !== '' && !pages.includes(slug) && !pages.includes(`${slug}/index`));

const config = readFileSync('astro.config.mjs', 'utf8');
const slugs = [...config.matchAll(/slug: '([^']+)'/g)].map((m) => m[1]);

// A group may hand a whole directory to Starlight instead of listing it. Only
// one does — the 38 sections of the requirements document, which are generated
// and whose count changes whenever a slice closes. Listing those by hand is the
// guard asking to be edited on every commit, which is the guard being deleted.
// Everywhere else the listing stays manual on purpose: a new page SHOULD fail
// this until somebody decides where it goes.
const auto = [...config.matchAll(/autogenerate: \{ directory: '([^']+)' \}/g)].map((m) => m[1]);
const covered = (slug) => slugs.includes(slug) || auto.some((d) => slug.startsWith(`${d}/`));

const orphans = pages.filter((p) => !covered(p));
const dangling = slugs.filter((s) => !pages.includes(s));

if (orphans.length || dangling.length || baseless.length || dangling_links.length) {
	if (orphans.length) {
		console.error(`Pages missing from the sidebar (${orphans.length}):`);
		for (const p of orphans) console.error(`  - ${p}`);
	}
	if (dangling.length) {
		console.error(`Sidebar slugs with no page (${dangling.length}):`);
		for (const s of dangling) console.error(`  - ${s}`);
	}
	if (baseless.length) {
		console.error(
			`Internal links missing the "${BASE}" base (${baseless.length}) — ` +
				`these 404 in production:`,
		);
		for (const { file, href } of baseless) {
			console.error(`  - ${file}: ${href}  →  ${BASE}${href}`);
		}
	}
	if (dangling_links.length) {
		console.error(`Internal links pointing at no page (${dangling_links.length}):`);
		for (const { file, href } of dangling_links) console.error(`  - ${file}: ${href}`);
	}
	process.exit(1);
}
console.log(
	`sidebar OK — ${pages.length} pages, all reachable` +
		(auto.length ? ` (${auto.join(', ')} autogenerated)` : '') +
		`; links OK — every internal link carries "${BASE}" and lands somewhere`,
);
